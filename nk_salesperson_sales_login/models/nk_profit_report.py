# -*- coding: utf-8 -*-
"""
Salesperson monthly profit report.

    NET PROFIT = Sale Order Margin
                 - Monthly Salary
                 - Mobile Recharge
                 - Travel Expense
                 - Food Expense

Rows are generated by the reporting wizard (one row per salesperson per
month) and are temporary (TransientModel).
"""

from collections import defaultdict
from datetime import datetime, time

from dateutil.relativedelta import relativedelta

from odoo import fields, models


class NkSalespersonProfitReport(models.TransientModel):
    _name = "nk.salesperson.profit.report"
    _description = "Field Salesperson Monthly Profit Report"
    _order = "month desc, employee_id"

    # ------------------------------------------------------------------
    # PERFORMANCE LIMITS  ->  CHANGE HERE
    # Net profit % = Net Profit / Sales (untaxed) * 100
    # ------------------------------------------------------------------
    EXCELLENT_PERCENT = 20.0   # 20% or more      -> Excellent
    GOOD_PERCENT = 10.0        # 10% to 20%       -> Good
    AVERAGE_PERCENT = 5.0      # 5% to 10%        -> Average
    #                            0% to 5%         -> Poor
    #                            below 0 (loss)   -> Loss

    employee_id = fields.Many2one("hr.employee", string="Salesperson")
    month = fields.Char(string="Month")
    currency_id = fields.Many2one("res.currency", string="Currency")

    quotation_count = fields.Integer(string="Quotations (All)")
    order_count = fields.Integer(string="Confirmed Orders")
    sales_amount = fields.Monetary(string="Sales (Untaxed)")
    margin = fields.Monetary(string="Sale Order Margin")

    salary = fields.Monetary(string="Monthly Salary")
    mobile_recharge = fields.Monetary(string="Mobile Recharge")
    travel_expense = fields.Monetary(string="Travel Expense")
    food_expense = fields.Monetary(string="Food Expense")
    total_expense = fields.Monetary(string="Total Expense")

    net_profit = fields.Monetary(string="Net Profit / (Loss)")

    performance = fields.Selection(
        [
            ("excellent", "Excellent"),
            ("good", "Good"),
            ("average", "Average"),
            ("poor", "Poor"),
            ("loss", "Loss"),
        ],
        string="Performance",
    )

    # ------------------------------------------------------------------
    # PROFIT FORMULA  ->  CHANGE HERE
    # ------------------------------------------------------------------
    @staticmethod
    def _compute_profit(margin, salary, mobile_recharge, travel, food):
        total_expense = salary + mobile_recharge + travel + food
        net_profit = margin - total_expense
        return total_expense, net_profit

    # ------------------------------------------------------------------
    # PERFORMANCE RULE  ->  CHANGE HERE
    # ------------------------------------------------------------------
    def _get_performance(self, net_profit, sales_amount):
        if net_profit < 0:
            return "loss"
        if sales_amount <= 0:
            return "poor"
        percent = net_profit / sales_amount * 100
        if percent >= self.EXCELLENT_PERCENT:
            return "excellent"
        if percent >= self.GOOD_PERCENT:
            return "good"
        if percent >= self.AVERAGE_PERCENT:
            return "average"
        return "poor"

    # ------------------------------------------------------------------
    # DATA COLLECTION
    # ------------------------------------------------------------------
    @staticmethod
    def _iter_months(date_from, date_to):
        current = date_from.replace(day=1)
        while current <= date_to:
            yield current
            current += relativedelta(months=1)

    def generate_lines(self, employees, date_from, date_to):
        """Create and return the report lines for the given employees/period."""
        # All quotations + orders of the period (cancelled ones ignored)
        orders = self.env["sale.order"].sudo().search([
            ("nk_employee_id", "in", employees.ids),
            ("state", "!=", "cancel"),
            ("date_order", ">=", datetime.combine(date_from, time.min)),
            ("date_order", "<=", datetime.combine(date_to, time.max)),
        ])
        margin_map = defaultdict(float)
        sales_map = defaultdict(float)
        quotation_map = defaultdict(int)
        order_map = defaultdict(int)
        for order in orders:
            local_date = fields.Datetime.context_timestamp(self, order.date_order)
            key = (order.nk_employee_id.id, local_date.strftime("%Y-%m"))
            quotation_map[key] += 1
            if order.state not in ("sale", "done"):
                continue
            order_map[key] += 1
            margin_map[key] += order.margin
            sales_map[key] += order.amount_untaxed

        # Only APPROVED expenses are counted
        expenses = self.env["nk.salesperson.expense"].sudo().search([
            ("employee_id", "in", employees.ids),
            ("state", "=", "approved"),
            ("expense_date", ">=", date_from),
            ("expense_date", "<=", date_to),
        ])
        travel_map = defaultdict(float)
        food_map = defaultdict(float)
        for exp in expenses:
            key = (exp.employee_id.id, exp.expense_date.strftime("%Y-%m"))
            travel_map[key] += exp.travel_amount
            food_map[key] += exp.food_amount

        vals_list = []
        for employee in employees:
            for month_start in self._iter_months(date_from, date_to):
                month = month_start.strftime("%Y-%m")
                key = (employee.id, month)

                margin = margin_map[key]
                sales = sales_map[key]
                salary = employee.nk_salary or 0.0
                recharge = employee.nk_mobile_expense or 0.0
                travel = travel_map[key]
                food = food_map[key]

                if not any((margin, salary, recharge, travel, food, quotation_map[key])):
                    continue

                total_expense, net_profit = self._compute_profit(
                    margin, salary, recharge, travel, food)

                vals_list.append({
                    "employee_id": employee.id,
                    "month": month,
                    "currency_id": (employee.nk_currency_id
                                    or employee.company_id.currency_id).id,
                    "quotation_count": quotation_map[key],
                    "order_count": order_map[key],
                    "sales_amount": sales,
                    "margin": margin,
                    "salary": salary,
                    "mobile_recharge": recharge,
                    "travel_expense": travel,
                    "food_expense": food,
                    "total_expense": total_expense,
                    "net_profit": net_profit,
                    "performance": self._get_performance(net_profit, sales),
                })

        return self.create(vals_list)
